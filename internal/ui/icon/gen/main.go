// Command gen writes icons_gen.go of internal/ui/icon from the prototype's
// icon table (reference/prototype/index.html: `const IC={name:'path',...}`,
// the filled PLAY and PAUSE, and the triangle of the lesson row).
//
//	go run ./gen -in ../../../reference/prototype/index.html -out icons_gen.go
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"strings"
)

// ====================================================================
// ============================ Contracts =============================
// ====================================================================

var (
	// tableRE matches `const IC={ ... };` up to the line that closes it.
	tableRE = regexp.MustCompile(`(?s)const IC=\{(.*?)\};`)
	// entryRE matches one `name:'path'` of the table.
	entryRE = regexp.MustCompile(`([a-z0-9]+):'([^']+)'`)
	// playRE and pauseRE match the filled glyphs, `const PLAY='<svg ...>'`.
	playRE  = regexp.MustCompile(`const PLAY='<svg viewBox="0 0 24 24"[^>]*><path d="([^"]+)" fill="currentColor"/></svg>'`)
	pauseRE = regexp.MustCompile(`const PAUSE='<svg viewBox="0 0 24 24"[^>]*><path d="([^"]+)" fill="currentColor"/></svg>'`)
	// triRE matches the lesson row's triangle, `<path d="..." fill="${cur?'currentColor':'none'}" stroke="currentColor" stroke-width="2"/>`.
	triRE = regexp.MustCompile(`<path d="(M6 4l14 8-14 8z)" fill="\$\{cur\?'currentColor':'none'\}" stroke="currentColor" stroke-width="(\d+)"/>`)
)

// glyph is one icon of the output.
type glyph struct {
	id, path string
	// filled is true for a glyph drawn with fill and no stroke (PLAY, PAUSE).
	filled bool
	// stroke is the stroke width the glyph is drawn with by default, 0 for
	// the sprite's svg.i.
	stroke string
	// fillAlso is true for a stroked glyph that is also filled (the triangle
	// of the current lesson).
	fillAlso bool
	// note says where the glyph comes from.
	note string
}

// ====================================================================
// ========================== Main functions ==========================
// ====================================================================

func main() {
	in := flag.String("in", "", "the prototype's index.html")
	out := flag.String("out", "icons_gen.go", "the Go file to write")
	flag.Parse()
	if *in == "" {
		fmt.Fprintln(os.Stderr, "gen: -in is required")
		os.Exit(2)
	}
	html, err := os.ReadFile(*in)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	src, err := generate(string(html))
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil { //nolint:gosec // a source file
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

// generate returns the source of icons_gen.go for the page html.
func generate(html string) ([]byte, error) {
	table := tableRE.FindStringSubmatch(html)
	if table == nil {
		return nil, fmt.Errorf("the IC table is not in the page")
	}
	var gs []glyph
	for _, m := range entryRE.FindAllStringSubmatch(table[1], -1) {
		gs = append(gs, glyph{id: m[1], path: m[2], note: "IC." + m[1]})
	}
	if len(gs) == 0 {
		return nil, fmt.Errorf("the IC table is empty")
	}
	for _, f := range []struct {
		re   *regexp.Regexp
		id   string
		note string
	}{{playRE, "play", "PLAY"}, {pauseRE, "pause", "PAUSE"}} {
		m := f.re.FindStringSubmatch(html)
		if m == nil {
			return nil, fmt.Errorf("%s is not in the page", f.note)
		}
		gs = append(gs, glyph{id: f.id, path: m[1], filled: true, note: f.note + " (filled)"})
	}
	tri := triRE.FindStringSubmatch(html)
	if tri == nil {
		return nil, fmt.Errorf("the lesson row's triangle is not in the page")
	}
	gs = append(gs,
		glyph{id: "tri", path: tri[1], stroke: tri[2], note: "the lesson row's triangle (lesLine), outline"},
		glyph{id: "trifill", path: tri[1], stroke: tri[2], fillAlso: true, note: "the lesson row's triangle of the current lesson, filled"})

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/ui/icon/gen from reference/prototype/index.html; DO NOT EDIT.\n\n")
	b.WriteString("package icon\n\n")
	b.WriteString("// Name is an icon of the prototype: a key of its IC table, PLAY, PAUSE, or the\n")
	b.WriteString("// lesson row's triangle.\n")
	b.WriteString("type Name uint8\n\n")
	b.WriteString("// The icons, in the order of the prototype's table. NameUnknown draws nothing.\n")
	b.WriteString("const (\n\tNameUnknown Name = iota\n")
	for _, g := range gs {
		fmt.Fprintf(&b, "\t// %s is %s.\n\t%s\n", camel(g.id), g.note, camel(g.id))
	}
	b.WriteString("\tnameEnd\n)\n\n")
	b.WriteString("// ids are the prototype's keys of the icons.\n")
	b.WriteString("var ids = [nameEnd]string{\n")
	for _, g := range gs {
		fmt.Fprintf(&b, "\t%s: %q,\n", camel(g.id), g.id)
	}
	b.WriteString("}\n\n")
	b.WriteString("// defs are the icons' paths, a 24-unit box.\n")
	b.WriteString("var defs = [nameEnd]def{\n")
	for _, g := range gs {
		var fields []string
		fields = append(fields, fmt.Sprintf("path: %q", g.path))
		if g.filled {
			fields = append(fields, "filled: true")
		}
		if g.fillAlso {
			fields = append(fields, "fillAlso: true")
		}
		if g.stroke != "" {
			fields = append(fields, fmt.Sprintf("stroke: %s", g.stroke))
		}
		fmt.Fprintf(&b, "\t%s: {%s},\n", camel(g.id), strings.Join(fields, ", "))
	}
	b.WriteString("}\n")

	return format.Source(b.Bytes())
}

// ====================================================================
// ========================= Helper Functions =========================
// ====================================================================

// camel returns the Go name of a prototype key: "dl" gives Dl, "b10" B10.
func camel(id string) string {
	if id == "" {
		return ""
	}

	return strings.ToUpper(id[:1]) + id[1:]
}
