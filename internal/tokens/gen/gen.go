// Package gen turns the design tokens of reference/design/tokens.json into
// the Go source of package tokens. It reads the dark scheme only (the app has
// one scheme, PLAN D6), and it fails on any missing or unknown key, so that a
// change to the tokens cannot silently leave a constant behind.
package gen

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"regexp"
	"strconv"
	"strings"
)

// ====================================================================
// ============================ Contracts =============================
// ====================================================================

// ErrInvalid is returned for a tokens file that does not match the schema
// the generator expects.
var ErrInvalid = errors.New("invalid tokens")

// ====================================================================
// ============================= Creation =============================
// ====================================================================

// item maps a key of tokens.json to the Go name it is generated under.
type item struct {
	key, name string
}

// colorItems are the colours of the Palette, in field order.
var colorItems = []item{
	{"bg", "Bg"}, {"surface", "Surface"}, {"surface2", "Surface2"}, {"border", "Border"},
	{"text", "Text"}, {"text2", "Text2"}, {"text3", "Text3"}, {"primary", "Primary"},
	{"onPrimary", "OnPrimary"}, {"accentText", "AccentText"}, {"red", "Red"}, {"info", "Info"},
	{"success", "Success"}, {"warning", "Warning"}, {"danger", "Danger"}, {"scrim", "Scrim"},
}

// fontItems are the font families.
var fontItems = []item{{"display", "FontDisplay"}, {"body", "FontBody"}, {"mono", "FontMono"}}

// spaceItems, radiusItems, heightItems and layoutItems are the numeric scales.
var (
	spaceItems = []item{
		{"xs", "SpaceXs"}, {"sm", "SpaceSm"}, {"md", "SpaceMd"}, {"lg", "SpaceLg"},
		{"xl", "SpaceXl"}, {"2xl", "SpaceXXL"}, {"3xl", "SpaceXXXL"},
	}
	radiusItems = []item{
		{"sm", "RadiusSm"}, {"md", "RadiusMd"}, {"lg", "RadiusLg"}, {"xl", "RadiusXl"}, {"pill", "RadiusPill"},
	}
	heightItems = []item{
		{"button", "HeightButton"}, {"input", "HeightInput"}, {"lessonRow", "HeightLessonRow"},
		{"tabBar", "HeightTabBar"}, {"tvButton", "HeightTVButton"},
	}
	layoutItems = []item{
		{"grid", "LayoutGrid"}, {"mobileMargin", "LayoutMobileMargin"},
		{"tvSafeH", "LayoutTVSafeH"}, {"tvSafeV", "LayoutTVSafeV"},
	}
)

// shadowItems are the two shadows; motionItems are the millisecond timings
// and the TV focus scale.
var (
	shadowItems = []item{{"card", "ShadowCard"}, {"lift", "ShadowLift"}}
	motionItems = []item{{"fastMs", "MotionFast"}, {"baseMs", "MotionBase"}}
)

// rgbaRE reads the rgba(r,g,b,a) notation of tokens.json.
var rgbaRE = regexp.MustCompile(`^rgba\((\d+),(\d+),(\d+),(\d*\.?\d+)\)$`)

// hexRE reads the #RRGGBB notation of tokens.json.
var hexRE = regexp.MustCompile(`^#([0-9A-Fa-f]{6})$`)

// ====================================================================
// ========================== Main functions ==========================
// ====================================================================

// Generate returns the Go source of package tokens for the tokens file in
// tokensJSON. The output is gofmt-formatted and deterministic.
func Generate(tokensJSON []byte) ([]byte, error) {
	var f struct {
		Color  map[string][]string        `json:"color"`
		Font   map[string]string          `json:"font"`
		Space  map[string]float64         `json:"space"`
		Radius map[string]float64         `json:"radius"`
		Height map[string]float64         `json:"height"`
		Layout map[string]float64         `json:"layout"`
		Shadow map[string]string          `json:"shadow"`
		Motion map[string]json.RawMessage `json:"motion"`
	}
	if err := json.Unmarshal(tokensJSON, &f); err != nil {
		return nil, fmt.Errorf("gen: read tokens: %w: %w", ErrInvalid, err)
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/tokens/gen from reference/design/tokens.json. DO NOT EDIT.\n\n")
	b.WriteString("package tokens\n\n")
	b.WriteString("import (\n\t\"time\"\n\n\t\"github.com/gdeskdev/desk/foundation/core/color\"\n)\n\n")

	// Palette and the dark scheme.
	colors, err := section(f.Color, colorItems, "color", func(v []string) (string, error) {
		if len(v) == 0 {
			return "", fmt.Errorf("%w: empty colour array", ErrInvalid)
		}
		return colorExpr(v[0])
	})
	if err != nil {
		return nil, err
	}
	b.WriteString("// Palette is the colour scheme of the app.\ntype Palette struct {\n")
	for _, it := range colorItems {
		fmt.Fprintf(&b, "\t%s color.Color\n", it.name)
	}
	b.WriteString("}\n\n// Dark is the Night Stage scheme (tokens.json color.*[0]).\nvar Dark = Palette{\n")
	for _, it := range colorItems {
		fmt.Fprintf(&b, "\t%s: %s,\n", it.name, colors[it.key])
	}
	b.WriteString("}\n\n")

	// Fonts, scales and layout numbers.
	fonts, err := section(f.Font, fontItems, "font", func(v string) (string, error) {
		return strconv.Quote(v), nil
	})
	if err != nil {
		return nil, err
	}
	b.WriteString("// Font families.\nconst (\n")
	for _, it := range fontItems {
		fmt.Fprintf(&b, "\t%s = %s\n", it.name, fonts[it.key])
	}
	b.WriteString(")\n\n")

	for _, sc := range []struct {
		comment string
		items   []item
		values  map[string]float64
		name    string
	}{
		{"Spacing scale, in points.", spaceItems, f.Space, "space"},
		{"Corner radii, in points.", radiusItems, f.Radius, "radius"},
		{"Control heights, in points.", heightItems, f.Height, "height"},
		{"Layout numbers, in points.", layoutItems, f.Layout, "layout"},
	} {
		vals, err := section(sc.values, sc.items, sc.name, func(v float64) (string, error) {
			return num(v), nil
		})
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "// %s\nconst (\n", sc.comment)
		for _, it := range sc.items {
			fmt.Fprintf(&b, "\t%s float32 = %s\n", it.name, vals[it.key])
		}
		b.WriteString(")\n\n")
	}

	// Motion: timings are durations, the focus scale is a factor.
	motion := make(map[string]float64, len(motionItems)+1)
	for _, it := range append(motionItems, item{"tvFocusScale", "TVFocusScale"}) {
		raw, ok := f.Motion[it.key]
		if !ok {
			return nil, fmt.Errorf("gen: motion.%s missing: %w", it.key, ErrInvalid)
		}
		var v float64
		if err := json.Unmarshal(raw, &v); err != nil {
			return nil, fmt.Errorf("gen: motion.%s: %w: %w", it.key, ErrInvalid, err)
		}
		motion[it.key] = v
	}
	// The easing (a CSS curve name) is read by the theme, not generated here.
	if _, ok := f.Motion["easing"]; !ok || len(f.Motion) != len(motionItems)+2 {
		return nil, fmt.Errorf("gen: motion has unknown keys: %w", ErrInvalid)
	}
	b.WriteString("// Motion timings and the Apple TV focus scale.\nconst (\n")
	for _, it := range motionItems {
		fmt.Fprintf(&b, "\t%s = %s * time.Millisecond\n", it.name, num(motion[it.key]))
	}
	fmt.Fprintf(&b, "\tTVFocusScale float32 = %s\n)\n\n", num(motion["tvFocusScale"]))

	// Shadows.
	shadows, err := section(f.Shadow, shadowItems, "shadow", shadowExpr)
	if err != nil {
		return nil, err
	}
	b.WriteString("// Shadow is a drop shadow: vertical offset, blur radius and colour.\n")
	b.WriteString("type Shadow struct {\n\tY, Blur float32\n\tColor   color.Color\n}\n\n")
	b.WriteString("// Shadows of the cards and of the lifted sheets.\nvar (\n")
	for _, it := range shadowItems {
		fmt.Fprintf(&b, "\t%s = %s\n", it.name, shadows[it.key])
	}
	b.WriteString(")\n")

	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gen: format: %w", err)
	}
	return out, nil
}

// ====================================================================
// ========================= Helper Functions =========================
// ====================================================================

// section looks up every item of a tokens section, in order, and converts
// each value. It fails on a missing key or on a key the generator does not
// know.
func section[V any, R any](m map[string]V, items []item, name string, conv func(V) (R, error)) (map[string]R, error) {
	if len(m) != len(items) {
		return nil, fmt.Errorf("gen: %s has %d keys, want %d: %w", name, len(m), len(items), ErrInvalid)
	}
	out := make(map[string]R, len(items))
	for _, it := range items {
		v, ok := m[it.key]
		if !ok {
			return nil, fmt.Errorf("gen: %s.%s missing: %w", name, it.key, ErrInvalid)
		}
		r, err := conv(v)
		if err != nil {
			return nil, fmt.Errorf("gen: %s.%s: %w", name, it.key, err)
		}
		out[it.key] = r
	}
	return out, nil
}

// colorExpr turns #RRGGBB or rgba(r,g,b,a) into a color.RGB or color.RGBA
// expression.
func colorExpr(s string) (string, error) {
	if m := hexRE.FindStringSubmatch(s); m != nil {
		v, err := strconv.ParseUint(m[1], 16, 32)
		if err != nil {
			return "", fmt.Errorf("%w: colour %q", ErrInvalid, s)
		}
		return fmt.Sprintf("color.RGB(%#02x, %#02x, %#02x)", v>>16&0xff, v>>8&0xff, v&0xff), nil
	}
	if m := rgbaRE.FindStringSubmatch(s); m != nil {
		for _, c := range m[1:3] {
			if n, err := strconv.Atoi(c); err != nil || n > 255 {
				return "", fmt.Errorf("%w: colour %q", ErrInvalid, s)
			}
		}
		n0, _ := strconv.Atoi(m[1])
		n1, _ := strconv.Atoi(m[2])
		n2, _ := strconv.Atoi(m[3])
		if n0 > 255 || n1 > 255 || n2 > 255 {
			return "", fmt.Errorf("%w: colour %q", ErrInvalid, s)
		}
		return fmt.Sprintf("color.RGBA(%d, %d, %d, %s)", n0, n1, n2, m[4]), nil
	}
	return "", fmt.Errorf("%w: colour %q", ErrInvalid, s)
}

// shadowExpr turns "0 12 28 rgba(0,0,0,.28)" into a Shadow literal. The
// horizontal offset must be 0, because Shadow has no X field.
func shadowExpr(s string) (string, error) {
	f := strings.Fields(s)
	if len(f) != 4 || f[0] != "0" {
		return "", fmt.Errorf("%w: shadow %q", ErrInvalid, s)
	}
	col, err := colorExpr(f[3])
	if err != nil {
		return "", err
	}
	return fmt.Sprintf("Shadow{Y: %s, Blur: %s, Color: %s}", f[1], f[2], col), nil
}

// num formats v as a Go float literal without exponent or trailing zeros.
func num(v float64) string {
	return strconv.FormatFloat(v, 'f', -1, 64)
}
