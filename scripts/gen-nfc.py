#!/usr/bin/env python3
"""Write the composition table of format.NFC and its test vectors.

Usage: scripts/gen-nfc.py   (any python3; it needs only the standard library)

Writes:

  internal/format/nfc_table.go   the canonical pairs (base, combining mark of
      U+0300-036F) -> primary composite of Unicode (composition exclusions
      left out, as NFC leaves them out), sorted twice: by (base, mark) for
      composing and by composite for decomposing; and the canonical
      combining class of every mark of U+0300-036F.
  internal/format/testdata/nfc.txt   test vectors, "input<TAB>NFC" as
      space-separated hex code points, NFC computed by Python's
      unicodedata (an implementation independent of the table): every
      Vietnamese letter decomposed (NFD), in the "to hop" form (precomposed
      vowel letter, separate tone mark), with its marks in reverse order,
      and the decomposed form of every composite of the table.

The app's text from the API may be decomposed (NFD): gotext, Android's text
engine, draws a combining mark as a glyph of its own beside its letter, so
format.NFC composes it at the API boundary (internal/api).
"""
import itertools
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARKS = range(0x0300, 0x0370)


def pairs():
    """Yields (composite, base, mark) for every primary composite."""
    for cp in range(0x110000):
        if 0xAC00 <= cp <= 0xD7A3:  # Hangul syllables compose by algorithm
            continue
        d = unicodedata.decomposition(chr(cp))
        if not d or d.startswith("<"):
            continue
        parts = [int(x, 16) for x in d.split()]
        if len(parts) != 2 or parts[1] not in MARKS:
            continue
        if unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) != chr(cp):
            continue  # a composition exclusion
        yield cp, parts[0], parts[1]


def go_table(entries):
    """Returns the Go source of the tables."""
    out = [
        "// Code generated by scripts/gen-nfc.py from Python's unicodedata "
        f"{unicodedata.unidata_version}. DO NOT EDIT.",
        "",
        "package format",
        "",
        "// nfcPairs are the primary composites whose mark is in U+0300-036F,",
        "// sorted by base, then mark: {base, mark, composite}.",
        "var nfcPairs = [...]nfcPair{",
    ]
    for cp, b, m in sorted(entries, key=lambda e: (e[1], e[2])):
        out.append(f"\t{{0x{b:04X}, 0x{m:04X}, 0x{cp:04X}}},")
    out += [
        "}",
        "",
        "// nfcSplits are the same composites sorted by composite.",
        "var nfcSplits = [...]nfcPair{",
    ]
    for cp, b, m in sorted(entries):
        out.append(f"\t{{0x{b:04X}, 0x{m:04X}, 0x{cp:04X}}},")
    out += [
        "}",
        "",
        "// markClass is the canonical combining class of U+0300-036F.",
        "var markClass = [0x70]uint8{",
    ]
    classes = [unicodedata.combining(chr(c)) for c in MARKS]
    for i in range(0, len(classes), 16):
        out.append("\t" + " ".join(f"{c}," for c in classes[i:i + 16]))
    out += ["}", ""]
    return "\n".join(out)


def vietnamese():
    """Returns every Vietnamese letter, lower and upper case, precomposed."""
    vowels = "a\u0103\u00e2e\u00eaio\u00f4\u01a1u\u01b0y"
    tones = ["", "\u0300", "\u0301", "\u0303", "\u0309", "\u0323"]
    out = []
    for v in vowels:
        for t in tones:
            s = unicodedata.normalize("NFC", v + t)
            out += [s, s.upper()]
    return out + ["\u0111", "\u0110"]


def hexs(s):
    return " ".join(f"{ord(c):04X}" for c in s)


def vectors(entries):
    """Yields (input, NFC) pairs."""
    seen = set()

    def add(s):
        if s not in seen:
            seen.add(s)
            yield s, unicodedata.normalize("NFC", s)

    for letter in vietnamese():
        nfd = unicodedata.normalize("NFD", letter)
        yield from add(nfd)
        # Reversed marks: a non-canonical order a typing tool may write.
        yield from add(nfd[0] + nfd[1:][::-1])
        # "To hop": the vowel letter precomposed, the tone mark apart.
        if len(nfd) >= 2 and unicodedata.combining(nfd[-1]):
            yield from add(unicodedata.normalize("NFC", nfd[:-1]) + nfd[-1])
        # Every permutation of the marks, in a word.
        for perm in itertools.permutations(nfd[1:]):
            yield from add("T" + nfd[0] + "".join(perm) + "ng")
    for cp, _, _ in entries:
        yield from add(unicodedata.normalize("NFD", chr(cp)))
    # Marks that do not compose stay, in canonical order.
    for s in ["x\u0301", "a\u0301\u0301", "\u0301a", "a\u0301\u0360", "q\u0302\u0323"]:
        yield from add(s)


def main():
    entries = list(pairs())
    (ROOT / "internal/format/nfc_table.go").write_text(go_table(entries))
    lines = [f"{hexs(a)}\t{hexs(b)}" for a, b in vectors(entries)]
    (ROOT / "internal/format/testdata/nfc.txt").write_text("\n".join(lines) + "\n")
    print(f"nfc: {len(entries)} composites, {len(lines)} vectors (Unicode {unicodedata.unidata_version})")


if __name__ == "__main__":
    sys.exit(main())
